export const locales = { en, de }

function merge<T>(base: T, override: unknown): T {
  if (!override || typeof override !== 'object') return base
  const out: Record<string, unknown> = { ...(base as Record<string, unknown>) }
  for (const [k, v] of Object.entries(override as Record<string, unknown>)) {
    out[k] = v && typeof v === 'object' ? merge((base as Record<string, unknown>)[k], v) : v
  }
  return out as T
}

export function resolveMessages(locale: 'en' | 'de' | Messages = 'en', overrides?: MessagesOverride): Messages {
  const base = typeof locale === 'string' ? locales[locale] : locale
  return merge(base, overrides)
}

/** `format('{count} rows', { count: 1200 }, 'en')` → `1,200 rows` */
export function format(template: string, vars: Record<string, string | number> = {}, lang = 'en'): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) => {
    const v = vars[k]
    if (v === undefined) return `{${k}}`
    return typeof v === 'number' ? v.toLocaleString(lang) : v
  })
}
